// Runs against the local stack; creates and removes only its own test records.
import {chromium,expect} from '@playwright/test';
import sharp from 'sharp';
import {mkdir} from 'node:fs/promises';
const base=process.env.APP_ORIGIN||'http://localhost:12000';
const directus=process.env.DIRECTUS_URL||'http://localhost:12001';
if(!['localhost','127.0.0.1'].includes(new URL(base).hostname))throw new Error('Integration checks require a local APP_ORIGIN');
const created=[];let fileId;
const browser=await chromium.launch({headless:true,...(process.env.BROWSER_PATH?{executablePath:process.env.BROWSER_PATH}:process.platform==='win32'?{channel:'msedge'}:{})});
const context=await browser.newContext({viewport:{width:1440,height:1100}});
const anonymous=await browser.newContext();
const page=await context.newPage();
const errors=[];
page.on('pageerror',error=>errors.push(error.message));
const prefix=`QA-${Date.now()}`;
async function add(collection,payload){const response=await context.request.post(`${base}/api/records/${collection}`,{headers:{Origin:base},data:payload});if(!response.ok())throw new Error(`${collection} create: ${response.status()} ${await response.text()}`);const row=await response.json();created.push([collection,row.id]);return row;}
try {
  await page.goto(`${base}/manage`);
  await page.getByLabel('メールアドレス').fill(process.env.ADMIN_EMAIL);
  await page.getByLabel('パスワード').fill(process.env.ADMIN_PASSWORD);
  await page.getByRole('button',{name:'ログイン',exact:true}).click();
  await expect(page.getByRole('heading',{name:'記録を管理.'})).toBeVisible({timeout:45000});
  console.log('PASS: administrator login');
  const a=await add('airports',{name:`${prefix} 羽田`,iata:'QHA',icao:`${prefix}-A`,latitude:35.55,longitude:139.78,timezone:'Asia/Tokyo',country:'JP'});
  const b=await add('airports',{name:`${prefix} San Francisco`,iata:'QSF',icao:`${prefix}-B`,latitude:37.62,longitude:-122.38,timezone:'America/Los_Angeles',country:'US'});
  const airline=await add('airlines',{name:`${prefix} Airline`,iata:'QA'});
  const aircraft=await add('aircraft',{registration:`${prefix}-REG`,airline:airline.id});
  await page.goto(`${base}/manage/flights`);
  await page.getByRole('button',{name:'新規登録'}).click();
  await page.getByLabel('便名').fill(prefix);
  await page.getByRole('combobox',{name:'出発空港',exact:true}).selectOption(a.id);
  await page.getByRole('combobox',{name:'到着空港',exact:true}).selectOption(b.id);
  await page.getByLabel('予定出発日時', {exact:false}).fill('2025-01-03T17:00');
  await page.getByLabel('予定到着日時', {exact:false}).fill('2025-01-03T10:00');
  await page.getByRole('combobox',{name:'搭乗機',exact:true}).selectOption(aircraft.id);
  await page.getByRole('combobox',{name:'航空会社',exact:true}).selectOption(airline.id);
  await page.getByRole('button',{name:'保存する'}).click();
  await expect(page.getByRole('heading',{name:/実績入力待ち/})).toBeVisible({timeout:20000});
  const flights=await (await context.request.get(`${base}/api/records/flights`)).json();
  const flight=flights.find(row=>row.flight_number===prefix);if(!flight)throw new Error('Flight was not saved');
  created.push(['flights',flight.id]);
  expect(flight.scheduled_departure).toMatch(/^2025-01-03T08:00:00/);
  expect(flight.scheduled_arrival).toMatch(/^2025-01-03T18:00:00/);
  console.log('PASS: web form creates a flight, converts both timezones, shows pending confirmation');
  await page.goto(`${base}/manage/flights?edit=${flight.id}`);
  await page.getByRole('combobox',{name:/状態/}).selectOption('flown');
  await page.getByLabel('実際の出発日時', {exact:false}).fill('2025-01-03T17:15');
  await page.getByLabel('実際の到着日時', {exact:false}).fill('2025-01-03T10:10');
  await page.getByRole('button',{name:'保存する'}).click();
  await expect(page.getByText(`${prefix} · 2025.01.03`,{exact:true})).toHaveCount(0);
  await expect(page.getByRole('button',{name:new RegExp(`${prefix}.*搭乗済み`)})).toBeVisible({timeout:20000});
  console.log('PASS: edit/confirm planned flight');
  const bytes=await sharp({create:{width:1000,height:700,channels:3,background:'#568090'}}).png().toBuffer();
  await page.goto(`${base}/manage/photos`);
  await page.getByRole('button',{name:'新規登録'}).click();
  await page.getByLabel('タイトル').fill(prefix);
  await page.getByLabel('画像ファイル',{exact:true}).setInputFiles({name:'test.png',mimeType:'image/png',buffer:bytes});
  await expect(page.getByText('アップロード済み',{exact:true})).toBeVisible({timeout:20000});
  await page.getByRole('combobox',{name:/公開範囲/}).selectOption('private');
  await page.getByRole('combobox',{name:'関連フライト',exact:true}).selectOption(flight.id);
  await page.getByRole('combobox',{name:'航空機',exact:true}).selectOption(aircraft.id);
  await page.getByLabel('タグ（カンマ区切り）').fill('integration, test');
  await page.getByLabel('撮影日',{exact:true}).fill('2025-01-03');
  await page.getByRole('button',{name:'保存する'}).click();
  await expect(page.getByRole('button',{name:new RegExp(`${prefix}.*非公開`)})).toBeVisible({timeout:20000});
  const photo=(await (await context.request.get(`${base}/api/records/photos`)).json()).find(row=>row.title===prefix);
  if(!photo)throw new Error('Photo was not saved');
  created.push(['photos',photo.id]);fileId=photo.file;
  const photoPayload={title:prefix,file:fileId,visibility:'private',flight:flight.id,aircraft:aircraft.id,tags:['integration'],taken_on:'2025-01-03'};
  const image=`${base}/api/photos/${photo.id}/image`;
  expect((await anonymous.request.get(image)).status()).toBe(404);
  expect((await anonymous.request.get(`${base}/photos/${photo.id}`)).status()).toBe(404);
  expect((await (await anonymous.request.get(`${base}/api/records/photos`)).json()).some(row=>row.id===photo.id)).toBe(false);
  const thumb=await context.request.get(image);expect(thumb.status()).toBe(200);expect(thumb.headers()['cache-control']).toContain('no-store');
  const metadata=await sharp(await thumb.body()).metadata();expect(metadata.width).toBeLessThanOrEqual(640);
  const patch=await context.request.patch(`${base}/api/records/photos`,{headers:{Origin:base},data:{...photoPayload,id:photo.id,visibility:'public'}});expect(patch.status()).toBe(200);
  expect((await anonymous.request.get(image)).status()).toBe(200);
  expect((await anonymous.request.get(image+'?original=1')).status()).toBe(404);
  const original=await context.request.get(image+'?original=1');expect(original.status()).toBe(200);expect(Buffer.compare(await original.body(),bytes)).toBe(0);
  await context.request.patch(`${base}/api/records/photos`,{headers:{Origin:base},data:{...photoPayload,id:photo.id}});
  expect((await anonymous.request.get(image)).status()).toBe(404);
  expect((await anonymous.request.get(`${directus}/assets/${fileId}`)).status()).toBe(403);
  console.log('PASS: upload, resize, original preservation, private/public/private transition, direct asset protection');
  expect((await anonymous.request.post(`${base}/api/records/categories`,{headers:{Origin:base},data:{name:'blocked'}})).status()).toBe(403);
  expect((await context.request.post(`${base}/api/records/categories`,{headers:{Origin:'https://evil.example'},data:{name:'blocked'}})).status()).toBe(403);
  console.log('PASS: anonymous writes and cross-origin writes blocked');
  const rename=await context.request.patch(`${base}/api/records/aircraft`,{headers:{Origin:base},data:{id:aircraft.id,registration:`${prefix}-NEW`,airline:airline.id}});
  expect(rename.status()).toBe(200);
  const savedFlights=await (await context.request.get(`${base}/api/records/flights`)).json();
  expect(savedFlights.find(row=>row.id===flight.id).registration).toBe(`${prefix}-REG`);
  console.log('PASS: historical registration survives a master-data edit');
  await page.goto(base);
  await expect(page.getByRole('link',{name:prefix,exact:true})).toBeVisible();
  await expect(page.locator('.leaflet-container')).toBeVisible();
  await mkdir('.local',{recursive:true});
  await page.screenshot({path:'.local/desktop.png',fullPage:true});
  await page.getByLabel('フライト検索').fill('non-existent-flight');
  await expect(page.getByRole('link',{name:prefix,exact:true})).toHaveCount(0);
  await page.getByLabel('フライト検索').fill('');
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'.local/mobile.png',fullPage:true});
  const overflow=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth,items:[...document.querySelectorAll('body *')].filter(e=>e.getBoundingClientRect().right>innerWidth+5).map(e=>({tag:e.tagName,c:String(e.className),right:e.getBoundingClientRect().right})).slice(0,30)}));
  if(overflow.scroll>overflow.width)console.log('Overflow diagnostic:',overflow);
  expect(overflow.scroll<=overflow.width).toBe(true);
  expect(errors).toEqual([]);
  console.log('PASS: desktop/mobile rendering, search, no horizontal overflow or browser runtime errors');
  await Promise.all([
    page.waitForResponse(response=>response.url().endsWith('/api/auth')&&response.request().method()==='DELETE'),
    page.getByRole('button',{name:'ログアウト'}).click(),
  ]);
  await page.goto(`${base}/manage`);
  await expect(page.getByRole('button',{name:'ログイン',exact:true})).toBeVisible();
  console.log('PASS: logout');
} finally {
  for(const [collection,id] of created.reverse()) {
    const result=await fetch(`${directus}/items/${collection}/${id}`,{method:'DELETE',headers:{Authorization:`Bearer ${process.env.ARCHIVE_TOKEN}`}});
    if(!result.ok)console.error(`Cleanup failed: ${collection} ${id} (${result.status})`);
  }
  if(fileId)await fetch(`${directus}/files/${fileId}`,{method:'DELETE',headers:{Authorization:`Bearer ${process.env.ARCHIVE_TOKEN}`}});
  await browser.close();
}
